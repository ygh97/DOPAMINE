// eps: true 인 기업 뉴스는 EPS(적정가)도 더 움직인다.
// 자리표시: {name} 종목 이름, {sym} 티커, {product} 주력 제품, {tech} 신흥주 기술, {sector} 업종,
//          {pct} 이번 움직임 크기에 맞춘 숫자, {n} 작은 정수, {amount} 금액 문구, {peers} 관련 종목,
//          {firm} {analyst} {target} 애널리스트 리포트
export interface Template { h: string; b: string; eps?: boolean }
interface GoodBad { good: Template[]; bad: Template[] }
/** 2단계로 이어지는 뉴스: 예고(또는 루머) → 결과(좋음 / 나쁨) */
interface Staged { pre: Template[]; good: Template[]; bad: Template[] }
export interface NewsTemplates {
  market: GoodBad;
  sector: GoodBad;
  /** 업종별 전용 문구. 업종 뉴스는 공통 + 전용에서 고른다 */
  sectorOnly: Record<string, GoodBad>;
  company: GoodBad;
  coin: GoodBad;
  /** 신흥주 3단계 검증: [최초 보도, 추가 확인, 성공, 실패] 단계마다 여러 문구 */
  venture: Template[][];
  listing: Record<"graduate" | "delist" | "ipo" | "split" | "watch" | "release" | "acquire" | "raise", Template>;
  noise: Template[];
  /** 경제지표: 예고 → 발표. good = 시장에 좋은 결과 */
  macro: { name: string; pre: Template; good: Template[]; bad: Template[]; flat: Template[] }[];
  rumor: Staged;
  earnings: { season: Template; good: Template[]; bad: Template[] };
  chain: GoodBad;
  launch: { pre: Template[]; good: Template[]; sellNews: Template[]; bad: Template[] };
  disclosure: Template[];
  whale: GoodBad;
  etf: Staged;
  meme: { pump: Template[]; dump: Template[] };
  report: { buy: Template[]; hold: Template[]; sell: Template[] };
}

